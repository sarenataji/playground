/**
 * SIGN 1 (Original Abstract Minimalist Wave Signature)
 * Saved here so you can easily switch back to it anytime.
 */
export function Sign1({
  triggerRef,
  className = "signature",
}: {
  triggerRef?: RefObject<HTMLElement | null>;
  className?: string;
}) {
  const svgRef = useRef<SVGSVGElement>(null);

  useGSAP(
    () => {
      if (prefersReducedMotion()) return;
      gsap.fromTo(
        ".sig-path-1",
        { strokeDashoffset: 480 },
        {
          strokeDashoffset: 0,
          duration: 1.8,
          ease: "power2.inOut",
          scrollTrigger: {
            trigger: triggerRef?.current ?? svgRef.current,
            start: "top 70%",
          },
        },
      );
    },
    { scope: svgRef, dependencies: [triggerRef] },
  );

  return (
    <svg
      ref={svgRef}
      className={className}
      viewBox="0 0 420 140"
      fill="none"
      aria-label="Sarena (Sign 1)"
    >
      <path
        className="sig-path-1"
        d="M20 90 C 40 40, 80 40, 90 88 C 98 128, 70 120, 78 80 C 110 20, 170 30, 190 86 C 200 118, 230 40, 270 70 C 300 94, 320 40, 360 78 C 380 96, 400 88, 408 72"
        stroke="currentColor"
        strokeWidth="2.2"
        strokeLinecap="round"
        strokeLinejoin="round"
        pathLength={480}
        style={{ strokeDasharray: 480 }}
      />
    </svg>
  );
}

